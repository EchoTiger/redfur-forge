package com.fissal.forge.auth

import kotlinx.serialization.Serializable

@Serializable
data class NetscapeCookieRecord(
    val domain: String,
    val includeSubdomains: Boolean,
    val path: String = "/",
    val secure: Boolean = true,
    val expiresEpochSec: Long = 0L,
    val name: String,
    val value: String,
    val httpOnly: Boolean = false
)

data class CookieImportResult(
    val cookies: List<NetscapeCookieRecord>,
    val skippedMalformedCount: Int,
    val skippedExpiredCount: Int
)

/**
 * Serializes and parses Netscape HTTP Cookie File (`cookies.txt`) records plus HTTP `Cookie:` headers.
 * Pure JVM (no android.* imports) so serialization security invariants can be unit-tested directly.
 */
object CookieNetscapeSerializer {

    private const val HTTP_ONLY_PREFIX = "#HttpOnly_"

    fun serialize(cookies: List<NetscapeCookieRecord>): String {
        val sb = StringBuilder()
        sb.append("# Netscape HTTP Cookie File\n")
        sb.append("# Generated by Redfur Forge\n")

        for (cookie in cookies) {
            val rawDomain = sanitizeField(cookie.domain)
                .trim()
                .removePrefixIgnoreCase(HTTP_ONLY_PREFIX)
                .trimStart('.')
                .lowercase()
            val sanitizedName = sanitizeField(cookie.name).trim()
            if (rawDomain.isEmpty() || sanitizedName.isEmpty()) continue

            val domainBody = if (cookie.includeSubdomains) ".$rawDomain" else rawDomain
            val domainField = if (cookie.httpOnly) "$HTTP_ONLY_PREFIX$domainBody" else domainBody
            val subdomainsFlag = if (cookie.includeSubdomains) "TRUE" else "FALSE"
            val sanitizedPath = sanitizeField(cookie.path).trim()
                .ifEmpty { "/" }
                .let { if (it.startsWith("/")) it else "/$it" }
            val secureFlag = if (cookie.secure) "TRUE" else "FALSE"
            val expiresField = cookie.expiresEpochSec.coerceAtLeast(0L)
            val sanitizedValue = sanitizeField(cookie.value)

            sb.append(domainField).append('\t')
                .append(subdomainsFlag).append('\t')
                .append(sanitizedPath).append('\t')
                .append(secureFlag).append('\t')
                .append(expiresField).append('\t')
                .append(sanitizedName).append('\t')
                .append(sanitizedValue).append('\n')
        }
        return sb.toString()
    }

    fun parseNetscapeCookiesTxt(
        rawText: String,
        nowEpochSec: Long = System.currentTimeMillis() / 1000L,
        filterDomain: String? = null
    ): CookieImportResult {
        val cleaned = rawText.removePrefix("\uFEFF")
        val normalizedFilter = filterDomain?.trim()?.let { normalizeDomainQuery(it) }?.takeIf { it.isNotEmpty() }

        val parsed = LinkedHashMap<Triple<String, String, String>, NetscapeCookieRecord>()
        var malformedCount = 0
        var expiredCount = 0

        for (rawLine in cleaned.split('\n')) {
            val line = rawLine.trimEnd('\r').removePrefix("\uFEFF")
            if (line.isBlank()) continue

            val trimmedStart = line.trimStart()
            val isHttpOnly = trimmedStart.startsWith(HTTP_ONLY_PREFIX, ignoreCase = true)
            val dataLine = if (isHttpOnly) {
                trimmedStart.substring(HTTP_ONLY_PREFIX.length)
            } else {
                if (trimmedStart.startsWith("#")) continue
                line
            }

            val cols = dataLine.split('\t')
            if (cols.size != 7) {
                malformedCount++
                continue
            }

            val rawDomainCol = sanitizeField(cols[0]).trim()
            val domainBare = rawDomainCol.trimStart('.').lowercase()
            if (domainBare.isEmpty()) {
                malformedCount++
                continue
            }

            val includeSubdomainsCol = parseBooleanStrict(cols[1].trim())
            val secureCol = parseBooleanStrict(cols[3].trim())
            val expiresEpochSec = cols[4].trim().toLongOrNull()
            val name = sanitizeField(cols[5]).trim()
            val value = sanitizeField(cols[6])

            if (includeSubdomainsCol == null ||
                secureCol == null ||
                expiresEpochSec == null ||
                expiresEpochSec < 0L ||
                name.isEmpty()
            ) {
                malformedCount++
                continue
            }

            if (expiresEpochSec in 1L until nowEpochSec) {
                expiredCount++
                continue
            }

            val includeSubdomains = includeSubdomainsCol || rawDomainCol.startsWith(".")
            val normalizedDomain = if (includeSubdomains) ".$domainBare" else domainBare
            val path = sanitizeField(cols[2]).trim().ifEmpty { "/" }

            if (normalizedFilter != null && !matchesDomain(normalizedDomain, includeSubdomains, normalizedFilter)) {
                continue
            }

            val record = NetscapeCookieRecord(
                domain = normalizedDomain,
                includeSubdomains = includeSubdomains,
                path = path,
                secure = secureCol,
                expiresEpochSec = expiresEpochSec,
                name = name,
                value = value,
                httpOnly = isHttpOnly
            )
            parsed[Triple(record.domain.lowercase(), record.path, record.name)] = record
        }

        return CookieImportResult(
            cookies = parsed.values.toList(),
            skippedMalformedCount = malformedCount,
            skippedExpiredCount = expiredCount
        )
    }

    fun parseCookieHeader(
        cookieHeader: String,
        domain: String,
        secure: Boolean = true
    ): List<NetscapeCookieRecord> {
        if (cookieHeader.isBlank() || domain.isBlank()) return emptyList()

        val normalizedDomain = normalizeCookieHeaderDomain(domain) ?: return emptyList()
        val includeSubdomains = normalizedDomain.startsWith(".")

        val deduped = LinkedHashMap<Triple<String, String, String>, NetscapeCookieRecord>()
        for (crumb in cookieHeader.split(';')) {
            val eqIndex = crumb.indexOf('=')
            if (eqIndex <= 0) continue

            val name = sanitizeField(crumb.substring(0, eqIndex)).trim()
            val value = sanitizeField(crumb.substring(eqIndex + 1)).trim()
            if (name.isEmpty()) continue

            val record = NetscapeCookieRecord(
                domain = normalizedDomain,
                includeSubdomains = includeSubdomains,
                path = "/",
                secure = secure,
                expiresEpochSec = 0L,
                name = name,
                value = value,
                httpOnly = false
            )
            deduped[Triple(record.domain.lowercase(), record.path, record.name)] = record
        }
        return deduped.values.toList()
    }

    fun hasAuthenticatedSession(
        cookies: List<NetscapeCookieRecord>,
        service: ServiceDescriptor,
        nowEpochSec: Long = System.currentTimeMillis() / 1000L
    ): Boolean {
        val active = cookies.filter { cookie ->
            cookie.name.isNotBlank() &&
                cookie.value.isNotBlank() &&
                (cookie.expiresEpochSec == 0L || cookie.expiresEpochSec >= nowEpochSec)
        }
        if (active.isEmpty()) return false
        if (service.requiredSessionCookieHints.isEmpty()) return true
        return active.any { cookie ->
            service.requiredSessionCookieHints.any { hint ->
                cookie.name.equals(hint, ignoreCase = true)
            }
        }
    }

    fun extractAccountOrDomainBadge(
        cookies: List<NetscapeCookieRecord>,
        service: ServiceDescriptor
    ): String? {
        val activeDomain = cookies
            .asSequence()
            .map { it.domain.trim().trimStart('.').lowercase() }
            .firstOrNull { it.isNotEmpty() }
            ?: service.hostMatchers.firstOrNull()?.lowercase()
            ?: return null
        return "@$activeDomain"
    }

    internal fun matchesDomain(
        cookieDomain: String,
        includeSubdomains: Boolean,
        targetHostOrDomain: String
    ): Boolean {
        val cookieBase = cookieDomain.trim().trimStart('.').lowercase()
        val targetBase = targetHostOrDomain.trim().trimStart('.').lowercase()
        if (cookieBase.isEmpty() || targetBase.isEmpty()) return false
        if (cookieBase == targetBase) return true
        if (cookieBase.endsWith(".$targetBase")) return true
        if ((includeSubdomains || cookieDomain.startsWith(".")) && targetBase.endsWith(".$cookieBase")) return true
        return false
    }

    private fun normalizeDomainQuery(raw: String): String {
        val extracted = if (raw.contains("://")) {
            ServiceCatalog.extractHost(raw).orEmpty()
        } else {
            raw.substringBefore('/').substringBefore(':')
        }
        return sanitizeField(extracted).trim().trimStart('.').lowercase()
    }

    private fun normalizeCookieHeaderDomain(rawDomain: String): String? {
        val cleaned = sanitizeField(rawDomain).trim()
        if (cleaned.isEmpty()) return null
        if (cleaned.contains("://")) {
            val host = ServiceCatalog.extractHost(cleaned) ?: return null
            return host.lowercase()
        }
        val bareOrDot = cleaned.substringBefore('/').substringBefore(':').lowercase()
        val bare = bareOrDot.trimStart('.')
        if (bare.isEmpty()) return null
        return if (bareOrDot.startsWith(".")) ".$bare" else bare
    }

    private fun parseBooleanStrict(raw: String): Boolean? = when {
        raw.equals("TRUE", ignoreCase = true) -> true
        raw.equals("FALSE", ignoreCase = true) -> false
        else -> null
    }

    private fun sanitizeField(raw: String): String =
        raw.replace("\r", "")
            .replace("\n", "")
            .replace("\t", "")
            .replace("\u0000", "")

    private fun String.removePrefixIgnoreCase(prefix: String): String =
        if (startsWith(prefix, ignoreCase = true)) substring(prefix.length) else this
}

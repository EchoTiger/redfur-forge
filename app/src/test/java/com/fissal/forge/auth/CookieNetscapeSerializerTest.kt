package com.fissal.forge.auth

import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertTrue
import org.junit.Test

class CookieNetscapeSerializerTest {

    @Test
    fun parseNetscapeCookiesTxt_parsesHttpOnlyBeforeSkippingComments() {
        val raw = buildString {
            append("\uFEFF# Netscape HTTP Cookie File\r\n")
            append("# Regular comment should be ignored\r\n")
            append("#HttpOnly_.youtube.com\tTRUE\t/\tTRUE\t1900000000\tSID\tsid_value_123\r\n")
            append("#httponly_www.youtube.com\tFALSE\t/watch\tFALSE\t0\tLOGIN_INFO\tlogin_tok\r\n")
            append(".youtube.com\tTRUE\t/\tTRUE\t0\tPREF\ttz=UTC\r\n")
        }

        val result = CookieNetscapeSerializer.parseNetscapeCookiesTxt(
            rawText = raw,
            nowEpochSec = 1700000000L
        )

        assertEquals(0, result.skippedMalformedCount)
        assertEquals(0, result.skippedExpiredCount)
        assertEquals(3, result.cookies.size)

        val sid = result.cookies[0]
        assertTrue(sid.httpOnly)
        assertEquals(".youtube.com", sid.domain)
        assertTrue(sid.includeSubdomains)
        assertEquals("/", sid.path)
        assertTrue(sid.secure)
        assertEquals(1900000000L, sid.expiresEpochSec)
        assertEquals("SID", sid.name)
        assertEquals("sid_value_123", sid.value)

        val loginInfo = result.cookies[1]
        assertTrue(loginInfo.httpOnly)
        assertEquals("www.youtube.com", loginInfo.domain)
        assertFalse(loginInfo.includeSubdomains)
        assertEquals("/watch", loginInfo.path)
        assertFalse(loginInfo.secure)
        assertEquals(0L, loginInfo.expiresEpochSec)

        val pref = result.cookies[2]
        assertFalse(pref.httpOnly)
        assertEquals("PREF", pref.name)
    }

    @Test
    fun parseNetscapeCookiesTxt_prunesExpiredWhileKeepingSessionAndFutureCookies() {
        val now = 1700000500L
        val raw = """
            .vimeo.com	TRUE	/	TRUE	0	vuid	session_cookie
            .vimeo.com	TRUE	/	TRUE	1700000499	old_tok	expired_val
            .vimeo.com	TRUE	/	TRUE	1700000500	edge_tok	still_valid
            .vimeo.com	TRUE	/	TRUE	1700009999	vimeo	active_val
        """.trimIndent()

        val result = CookieNetscapeSerializer.parseNetscapeCookiesTxt(raw, nowEpochSec = now)

        assertEquals(1, result.skippedExpiredCount)
        assertEquals(0, result.skippedMalformedCount)
        assertEquals(listOf("vuid", "edge_tok", "vimeo"), result.cookies.map { it.name })
    }

    @Test
    fun parseNetscapeCookiesTxt_countsMalformedLinesWithoutThrowing() {
        val raw = """
            # header
            .patreon.com	TRUE	/	TRUE	not_a_number	session_id	abc
            .patreon.com	TRUE	/	TRUE	1800000000		missing_name
            .patreon.com	TRUE	/	TRUE
            .patreon.com	MAYBE	/	TRUE	0	session_id	bad_flag
            .patreon.com	TRUE	/	TRUE	-5	session_id	negative_exp
            .patreon.com	TRUE	/	TRUE	0	session_id	good_value
        """.trimIndent()

        val result = CookieNetscapeSerializer.parseNetscapeCookiesTxt(raw, nowEpochSec = 1700000000L)

        assertEquals(5, result.skippedMalformedCount)
        assertEquals(0, result.skippedExpiredCount)
        assertEquals(1, result.cookies.size)
        assertEquals("good_value", result.cookies.single().value)
    }

    @Test
    fun serialize_sanitizesCrlfAndTabInjectionAndFormatsHttpOnlyAndSubdomains() {
        val cookies = listOf(
            NetscapeCookieRecord(
                domain = "www.twitch.tv",
                includeSubdomains = true,
                path = "/\r\n#injected",
                secure = true,
                expiresEpochSec = 1800000000L,
                name = "auth-token\tbad",
                value = "val\r\n.evil.com\tTRUE\t/\tFALSE\t0\thijack\t1",
                httpOnly = true
            ),
            NetscapeCookieRecord(
                domain = ".api.twitch.tv",
                includeSubdomains = false,
                path = "/",
                secure = false,
                expiresEpochSec = 0L,
                name = "twilight-user",
                value = "normal_value",
                httpOnly = false
            )
        )

        val serialized = CookieNetscapeSerializer.serialize(cookies)
        val lines = serialized.trimEnd('\n').split('\n')

        assertEquals("# Netscape HTTP Cookie File", lines[0])
        assertEquals("# Generated by Redfur Forge", lines[1])
        assertEquals(4, lines.size)

        val line1Cols = lines[2].split('\t')
        assertEquals(7, line1Cols.size)
        assertEquals("#HttpOnly_.www.twitch.tv", line1Cols[0])
        assertEquals("TRUE", line1Cols[1])
        assertEquals("/#injected", line1Cols[2])
        assertEquals("auth-tokenbad", line1Cols[5])
        assertFalse(line1Cols[6].contains('\r'))
        assertFalse(line1Cols[6].contains('\n'))
        assertFalse(line1Cols[6].contains('\t'))

        val line2Cols = lines[3].split('\t')
        assertEquals("api.twitch.tv", line2Cols[0])
        assertEquals("FALSE", line2Cols[1])
    }

    @Test
    fun parseCookieHeader_preservesBase64EqualsAndDeduplicates() {
        val header = "auth=YWJjMTIz==; malformed_crumb; theme=dark; auth=bmV3VG9rZW4=; nested=a=b=c"

        val subdomainRecords = CookieNetscapeSerializer.parseCookieHeader(
            cookieHeader = header,
            domain = ".patreon.com",
            secure = true
        )

        assertEquals(3, subdomainRecords.size)
        assertTrue(subdomainRecords.all { it.includeSubdomains && it.domain == ".patreon.com" })

        val byName = subdomainRecords.associateBy { it.name }
        assertEquals("bmV3VG9rZW4=", byName["auth"]?.value)
        assertEquals("dark", byName["theme"]?.value)
        assertEquals("a=b=c", byName["nested"]?.value)

        val hostOnlyRecords = CookieNetscapeSerializer.parseCookieHeader(
            cookieHeader = "token=abc==",
            domain = "members.example.com",
            secure = true
        )
        assertEquals(1, hostOnlyRecords.size)
        assertFalse(hostOnlyRecords.single().includeSubdomains)
        assertEquals("members.example.com", hostOnlyRecords.single().domain)
        assertEquals("abc==", hostOnlyRecords.single().value)
    }

    @Test
    fun parseNetscapeCookiesTxt_filtersTargetDomainAndSubdomains() {
        val raw = """
            .youtube.com	TRUE	/	TRUE	0	SID	yt_sid
            m.youtube.com	FALSE	/	TRUE	0	VISITOR	yt_mobile
            .google.com	TRUE	/	TRUE	0	HSID	goog_hsid
            .notyoutube.com	TRUE	/	TRUE	0	FAKE	nope
        """.trimIndent()

        val filtered = CookieNetscapeSerializer.parseNetscapeCookiesTxt(
            rawText = raw,
            nowEpochSec = 1700000000L,
            filterDomain = "youtube.com"
        )

        assertEquals(listOf("SID", "VISITOR"), filtered.cookies.map { it.name })
    }

    @Test
    fun hasAuthenticatedSession_andDomainBadgeRespectHintsAndNeverLeakSecrets() {
        val youtube = ServiceCatalog.findById("youtube")!!
        val unauthenticated = listOf(
            NetscapeCookieRecord(
                domain = ".youtube.com",
                includeSubdomains = true,
                name = "PREF",
                value = "secret_pref_value"
            )
        )
        assertFalse(CookieNetscapeSerializer.hasAuthenticatedSession(unauthenticated, youtube, 1700000000L))

        val authenticated = unauthenticated + NetscapeCookieRecord(
            domain = ".youtube.com",
            includeSubdomains = true,
            expiresEpochSec = 1800000000L,
            name = "SID",
            value = "super_secret_session_token_xyz"
        )
        assertTrue(CookieNetscapeSerializer.hasAuthenticatedSession(authenticated, youtube, 1700000000L))

        val expiredAuth = listOf(
            NetscapeCookieRecord(
                domain = ".youtube.com",
                includeSubdomains = true,
                expiresEpochSec = 1600000000L,
                name = "SID",
                value = "super_secret_session_token_xyz"
            )
        )
        assertFalse(CookieNetscapeSerializer.hasAuthenticatedSession(expiredAuth, youtube, 1700000000L))

        val badge = CookieNetscapeSerializer.extractAccountOrDomainBadge(authenticated, youtube)
        assertNotNull(badge)
        assertEquals("@youtube.com", badge)
        assertFalse(badge!!.contains("super_secret_session_token_xyz"))
        assertFalse(badge.contains("SID"))
    }
}
